-- The observability plane's own state.
--
-- These tables are not part of hyperswitch_db. They live in a database this plane owns, so that
-- alert state is not written into a store the application owns.
--
-- Two things are worth knowing before changing a column here:
--
--   * `json` and `jsonb` are not interchangeable. The columns holding values the dashboard sends
--     already serialised are `json`, which preserves the bytes it was given; `jsonb` re-encodes
--     and would hand back something different from what was saved.
--   * `alerts_main` records each announcement that was sent, separately from `alerts_intermediate`,
--     which holds current lifecycle state. Keeping them apart is what makes it possible to say
--     whether an alert was delivered.
--
-- Timestamps are naive TIMESTAMP, as elsewhere in this repository, which holds UTC by discipline
-- rather than by column type.
--
-- No column carries NOT NULL or DEFAULT. Required-ness and defaulting belong to the service, which
-- has to hold them anyway for stores that cannot express either, and a constraint declared in both
-- places is a constraint that can disagree with itself. Identifiers are generated by the caller
-- rather than by gen_random_uuid(), and last_updated_at is set by the handler rather than by
-- CURRENT_TIMESTAMP, which also settles whose clock the durations are counted against.
--
-- Primary keys stay: they are the identity of a row and the target of every upsert, not a
-- validation rule.

-- Alert definitions: one row per alert, and the whole of its configuration.
-- blacklist, snooze and thresholds live here as JSON rather than as side tables,
-- so everything about an alert is in one place.
CREATE TABLE IF NOT EXISTS alerts_info (
    id               UUID PRIMARY KEY,
    name             VARCHAR(64),
    product          VARCHAR(64),
    dimensions       VARCHAR(255),
    period           INTEGER,
    default_channel  VARCHAR(64),
    default_critical BOOLEAN,
    blacklist        JSON,
    snooze           JSON,
    history_window   INTEGER,
    thresholds       JSON,
    metadata         JSON,
    is_enabled       BOOLEAN,
    comments         JSON,
    call_period      INTEGER,
    author           VARCHAR(64),
    approver         VARCHAR(64),
    last_updated_at  TIMESTAMP,
    -- r-apps' upsert target, carried over unchanged: definitions are written with
    -- ON CONFLICT on exactly this tuple.
    --
    -- Postgres treats NULLs as distinct in a unique constraint, so with the NOT NULL
    -- constraints gone two rows differing only by a null author no longer collide. The
    -- service is what keeps these five columns populated; the constraint catches the
    -- duplicates it would otherwise write, not nulls it never writes.
    CONSTRAINT alerts_info_conflict UNIQUE (name, product, dimensions, is_enabled, author)
);

-- Announcements actually sent, one row per alert per delivery. `sent` and
-- `ts_slack` are the record that an alert reached a channel; without them a
-- failed delivery is indistinguishable from a successful one on the next run.
CREATE TABLE IF NOT EXISTS alerts_main (
    id              UUID PRIMARY KEY,
    name            VARCHAR(64),
    product         VARCHAR(64),
    dimensions      JSON,
    ts_slack        VARCHAR(255),
    ts_alert        TIMESTAMP,
    duration        INTEGER,
    sent            BOOLEAN,
    critical        BOOLEAN,
    rca_metadata    JSONB,
    metadata        JSON,
    last_updated_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ts_alert
    ON alerts_main USING btree (ts_alert);
CREATE INDEX IF NOT EXISTS idx_alerts_last_updated_at
    ON alerts_main USING btree (last_updated_at);

CREATE TABLE IF NOT EXISTS alerts_main_xyne (
    id              UUID PRIMARY KEY,
    name            VARCHAR(64),
    product         VARCHAR(64),
    dimensions      JSON,
    ts_slack        VARCHAR(255),
    ts_alert        TIMESTAMP,
    duration        INTEGER,
    sent            BOOLEAN,
    critical        BOOLEAN,
    rca_metadata    JSONB,
    metadata        JSON,
    last_updated_at TIMESTAMP
);

-- The xyne twin indexes ts_slack where the slack table indexes ts_alert, as r-apps has it: the
-- xyne reader looks alerts up by thread. Named apart because r-apps reuses one name across both
-- tables and Postgres index names are unique per schema.
CREATE INDEX IF NOT EXISTS idx_ts_alert_xyne
    ON alerts_main_xyne USING btree (ts_slack);
CREATE INDEX IF NOT EXISTS idx_xyne_alerts_last_updated_at
    ON alerts_main_xyne USING btree (last_updated_at);

-- Current lifecycle state: what is firing now, since when, and what recovered.
-- This is what the classifier diffs against; `alerts_main` is the log of what
-- was said about it.
CREATE TABLE IF NOT EXISTS alerts_intermediate (
    id_intermediate        UUID PRIMARY KEY,
    id                     UUID REFERENCES alerts_main(id) ON DELETE CASCADE,
    name                   VARCHAR(64),
    product                VARCHAR(64),
    dimensions             JSONB,
    ts_slack               VARCHAR(255),
    ts_alert               TIMESTAMP,
    latest_ts_alert        TIMESTAMP,
    max_duration           INTEGER,
    other_metrics          JSONB,
    metadata               JSONB,
    metadata_alert_details JSONB,
    rca_metadata           JSONB,
    group_id               VARCHAR(64),
    priority               VARCHAR(64),
    last_updated_at        TIMESTAMP,
    recovered_ts           TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ts
    ON alerts_intermediate USING btree (ts_alert, latest_ts_alert);

CREATE TABLE IF NOT EXISTS alerts_intermediate_xyne (
    id_intermediate        UUID PRIMARY KEY,
    id                     UUID REFERENCES alerts_main_xyne(id) ON DELETE CASCADE,
    name                   VARCHAR(64),
    product                VARCHAR(64),
    dimensions             JSONB,
    ts_slack               VARCHAR(255),
    ts_alert               TIMESTAMP,
    latest_ts_alert        TIMESTAMP,
    max_duration           INTEGER,
    other_metrics          JSONB,
    metadata               JSONB,
    metadata_alert_details JSONB,
    rca_metadata           JSONB,
    group_id               VARCHAR(64),
    priority               VARCHAR(64),
    last_updated_at        TIMESTAMP,
    recovered_ts           TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ts_xyne
    ON alerts_intermediate_xyne USING btree (ts_slack, latest_ts_alert);

-- The mappers screen. product and values_ are `json` rather than `jsonb`: the
-- dashboard sends them already serialised and reads them back expecting the
-- same bytes.
CREATE TABLE IF NOT EXISTS alerts_dicts (
    id         UUID PRIMARY KEY,
    name       VARCHAR(64),
    key_       VARCHAR(255),
    product    JSON,
    values_    JSON,
    ts_created TIMESTAMP,
    is_enabled BOOLEAN,
    username   VARCHAR(64),
    metadata   JSON
);

-- One enabled entry per name and key; superseded rows stay for history.
CREATE UNIQUE INDEX IF NOT EXISTS idx_alerts_dicts_enabled_unique
    ON alerts_dicts USING btree (name, key_) WHERE is_enabled IS TRUE;

CREATE INDEX IF NOT EXISTS idx_alerts_dicts_latest
    ON alerts_dicts USING btree (name, key_, ts_created DESC);

